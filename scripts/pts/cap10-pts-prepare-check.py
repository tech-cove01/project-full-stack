"""Offline packet/binding/cleanup checks; local Node bundle, no service/cloud."""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
from types import SimpleNamespace
import uuid
from unittest.mock import patch

SOURCE = Path(__file__).with_name('cap10-pts-prepare.py')
spec = importlib.util.spec_from_file_location('cap10_pts_prepare_checks', SOURCE)
prepare = importlib.util.module_from_spec(spec); spec.loader.exec_module(prepare)
checks = 0


def check(condition, name):
    global checks
    assert condition, name
    checks += 1
    print('PASS ' + name)


def rejected(fn, name):
    try:
        fn()
    except (ValueError, KeyError):
        check(True, name)
        return
    raise AssertionError(name)


def fixture(base):
    repo = base / 'repo'; root = repo / 'docs/evidence/2026-11-01-cap10/linux'
    root.mkdir(parents=True)
    runtime = base / ('.runtime-fullstack-cap10-' + uuid.uuid4().hex[:12]); runtime.mkdir(mode=0o700)
    def save(path, value):
        with Path(path).open('x', encoding='utf-8') as stream:
            json.dump(value, stream)
    def private_write(runtime, name, value):
        path = runtime / name
        save(runtime / ('owned-env-' + uuid.uuid4().hex + '.json'), {'path': str(path)})
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, 'w', encoding='utf-8') as stream:
            json.dump(value, stream)
        return path
    owned = SimpleNamespace(REPO=repo, ROOT=root, save=save, private_write=private_write,
        read=lambda path: json.loads(Path(path).read_text(encoding='utf-8')))
    values = {'CAP10_PLATFORM': 'linux', 'CAP10_RUNTIME': str(runtime), 'CAP10_EVIDENCE': str(root),
              'MYSQL_PASSWORD': 'PRIVATE-DB-SENTINEL', 'GO_FEED_DIAGNOSTICS': 'false'}
    environment = private_write(runtime, 'env-baseline.private.json', values)
    owned.settings = lambda path: (owned.read(path), runtime)
    return owned, runtime, environment


def main():
    workspace = SOURCE.resolve().parents[3]
    with tempfile.TemporaryDirectory(prefix='.qa-cap10-pts-prepare-', dir=workspace) as temporary:
        target = Path(temporary).resolve()
        assert target.parent == workspace and target.name.startswith('.qa-cap10-pts-prepare-')
        owned, runtime, environment = fixture(target / 'success')
        seen = []
        def runner(argv, **kwargs):
            data = json.loads(kwargs['input']); token = data['controlToken']
            directory = Path(data['directory'])
            registry = list(runtime.glob('owned-pts-upload-*.json'))
            assert len(registry) == 1 and not directory.exists()
            registered = owned.read(registry[0])
            assert registered['privateInputPath'] == str(directory / 'cap10-pts-private.json')
            assert token not in '\n'.join(argv) and 'PRIVATE-AK-SENTINEL' not in json.dumps(kwargs['env'])
            seen.append({'registeredFirst': True, 'secretNotInArgv': True})
            return subprocess.run(argv, **kwargs)
        def bundle(directory, url, token):
            return prepare.run_bundle(directory, url, token, runner=runner)
        with patch.dict(os.environ, {'ALIBABA_CLOUD_ACCESS_KEY_SECRET': 'PRIVATE-AK-SENTINEL'}):
            public = prepare.packet(owned, environment, '10.8.0.10', bundle_runner=bundle)
        check(len(seen) == 1, 'real local bundle receives secret only through stdin after exact cleanup registration')
        packet = Path(public['privatePaths']['packetDirectory'])
        cfg_path = Path(public['privatePaths']['configuration']); cfg = owned.read(cfg_path)
        derived = owned.read(public['privatePaths']['environment'])
        check(len(cfg['controlToken']) == 64 and cfg['sceneId'] == 'UNBOUND' and cfg['expectedEngines'] == 2, 'private unbound config has fixed collector contract')
        check(set(cfg['sceneFiles']) == set(prepare.UPLOAD_FILES) and all(cfg['sceneFiles'][name] == hashlib.md5((packet / name).read_bytes(), usedforsecurity=False).hexdigest() for name in prepare.UPLOAD_FILES), 'all three API file MD5 values match real generated bytes')
        check(derived['CAP10_LOAD_BACKEND'] == 'pts' and derived['API_ADDR'] == '0.0.0.0:8281' and derived['MYSQL_PASSWORD'] == 'PRIVATE-DB-SENTINEL', 'derived environment changes only required backend/listen wiring')
        check(public['manifest']['normalThreads'] == 512 and public['manifest']['ptsConcurrency'] == 513 and public['manifest']['csvSplitRequired'], 'generated standard JMX preserves 512 plus teardown and split CSV')
        check(cfg['controlToken'] not in json.dumps(public) and 'PRIVATE-DB-SENTINEL' not in json.dumps(public), 'public packet metadata exports no control or database credentials')
        original_cfg = cfg_path.read_bytes(); original_env = Path(public['privatePaths']['environment']).read_bytes()
        bound = prepare.bind(owned, public['privatePaths']['environment'], 'CAP10_EXISTING_SCENE')
        bound_cfg = owned.read(bound['privatePaths']['configuration'])
        check(bound_cfg['sceneId'] == 'CAP10_EXISTING_SCENE' and bound_cfg['controlToken'] == cfg['controlToken'] and bound_cfg['sceneFiles'] == cfg['sceneFiles'], 'bind preserves token and exact frozen upload file hashes')
        check(cfg_path.read_bytes() == original_cfg and Path(public['privatePaths']['environment']).read_bytes() == original_env, 'bind creates new private files and preserves original bytes')
        check(not bound['cloudCalled'] and not bound['sceneCreatedByThisTool'] and cfg['controlToken'] not in json.dumps(bound), 'binding existing SceneId does not call cloud or disclose a secret')
        rejected(lambda: prepare.bind(owned, public['privatePaths']['environment'], 'OTHER_SCENE'), 'second binding is rejected without overwriting metadata')
        rejected(lambda: prepare.packet(owned, environment, '10.8.0.10'), 'second packet generation is rejected')
        if os.name != 'nt':
            check(packet.stat().st_mode & 0o077 == 0 and (packet / 'cap10-pts-private.json').stat().st_mode & 0o077 == 0, 'real packet folder/file private permissions')
        for index, address in enumerate(('127.0.0.1', '8.8.8.8', '::1')):
            other, _, env = fixture(target / ('bad-ip-' + str(index)))
            rejected(lambda: prepare.packet(other, env, address), 'non-RFC1918 IPv4 rejected: ' + address)
        other, other_runtime, other_env = fixture(target / 'partial')
        def partial(directory, url, token):
            assert list(other_runtime.glob('owned-pts-upload-*.json'))
            directory.mkdir(mode=0o700)
            (directory / 'cap10-pts-private.json').write_text(token)
            raise ValueError('injected local bundle failure')
        rejected(lambda: prepare.packet(other, other_env, '192.168.2.10', bundle_runner=partial), 'partial bundle failure retains pre-registered exact recovery path')
        check(len(list(other_runtime.glob('owned-pts-upload-*.json'))) == 1, 'failed packet remains registered for exact cleanup')
        rejected(lambda: prepare.packet(other, other_env, '192.168.2.10'), 'partial setup cannot silently create a second packet')
        # Clean the actual generated packet, leaving all independently registered
        # private configurations/environments and an external credential intact.
        external = target / 'external-credential.private.json'; external.write_text('PRIVATE-EXTERNAL-SENTINEL')
        registry = Path(public['privatePaths']['cleanupRegistration']); registry_bytes = registry.read_bytes()
        private_files = {path: path.read_bytes() for path in runtime.glob('env*.private.json')}
        cleaned = prepare.cleanup_packet(owned, bound['privatePaths']['environment'])
        check(cleaned['complete'] and not packet.exists() and all(row['deleted'] for row in cleaned['entries'][0]['files']), 'complete packet cleanup deletes exactly three uploads plus manifest and empty parent')
        check(registry.read_bytes() == registry_bytes and all(path.read_bytes() == content for path, content in private_files.items()) and external.read_text() == 'PRIVATE-EXTERNAL-SENTINEL', 'cleanup preserves registration, private env/config and external credentials')
        check(cfg['controlToken'] not in json.dumps(cleaned) and owned.read(owned.ROOT / 'pts-packet-cleanup.json')['complete'] and not cleaned['cloudCalled'], 'public cleanup result records completed deletion without secret/cloud calls')
        rejected(lambda: prepare.cleanup_packet(owned, bound['privatePaths']['environment']), 'cleanup cannot overwrite prior cleanup evidence')
        partial_cleaned = prepare.cleanup_packet(other, other_env)
        check(partial_cleaned['complete'] and sum(row['deleted'] for row in partial_cleaned['entries'][0]['files']) == 1 and not Path(partial_cleaned['entries'][0]['packetDirectory']).exists(), 'partial bundle cleanup removes registered secret and tolerates never-written files')

        def registered(name, present=True):
            owner, run, env = fixture(target / name)
            nonce = uuid.uuid4().hex[:12]; directory = run / ('pts-upload-' + nonce)
            registration = run / ('owned-pts-upload-' + nonce + '.json')
            value = {'version': 1, 'parent': str(directory), 'privateInputPath': str(directory / 'cap10-pts-private.json'),
                'files': [str(directory / name) for name in prepare.PACKET_FILES], 'registeredBeforeSecretWrite': True}
            owner.save(registration, value)
            if present:
                directory.mkdir(mode=0o700)
                for filename in prepare.PACKET_FILES:
                    (directory / filename).write_text('PRIVATE-UPLOAD-SENTINEL')
            return owner, run, env, directory, registration, value

        absent, _, absent_env, absent_dir, _, _ = registered('never-created', present=False)
        check(prepare.cleanup_packet(absent, absent_env)['complete'] and not absent_dir.exists(), 'registration before failed directory creation can be cleanly closed')
        for kind in ('unknown-file', 'unknown-directory', 'registered-directory', 'foreign-parent', 'foreign-file', 'wrong-private', 'missing-file-registration', 'missing-proof', 'foreign-nonce'):
            owner, run, env, directory, registration, value = registered('reject-' + kind)
            sentinel = directory / 'cap10-pts-private.json'
            if kind == 'unknown-file':
                (directory / 'unknown.txt').write_text('DO-NOT-DELETE')
            elif kind == 'unknown-directory':
                (directory / 'unknown').mkdir()
            elif kind == 'registered-directory':
                (directory / 'slots.csv').unlink(); (directory / 'slots.csv').mkdir()
            elif kind == 'foreign-parent':
                value['parent'] = str(external.parent)
            elif kind == 'foreign-file':
                value['files'][0] = str(external)
            elif kind == 'wrong-private':
                value['privateInputPath'] = str(external)
            elif kind == 'missing-file-registration':
                value['files'].pop()
            elif kind == 'missing-proof':
                value['registeredBeforeSecretWrite'] = False
            else:
                value['parent'] = str(run / ('pts-upload-' + '0' * 12))
            registration.write_text(json.dumps(value), encoding='utf-8')
            rejected(lambda: prepare.cleanup_packet(owner, env), 'preflight rejects ' + kind)
            check(sentinel.read_text() == 'PRIVATE-UPLOAD-SENTINEL' and external.read_text() == 'PRIVATE-EXTERNAL-SENTINEL', 'rejection deletes no registered or external file: ' + kind)
        # A valid first registration cannot be deleted before a later invalid one
        # has been inspected; this catches per-registration validate/delete loops.
        owner, run, env, directory, _, _ = registered('all-preflight')
        other_directory = run / ('pts-upload-' + 'f' * 12)
        owner.save(run / ('owned-pts-upload-' + 'f' * 12 + '.json'), {'parent': str(other_directory), 'files': []})
        rejected(lambda: prepare.cleanup_packet(owner, env), 'all registrations must pass before first deletion')
        check(all((directory / name).is_file() for name in prepare.PACKET_FILES), 'later invalid registration preserves every earlier valid packet file')
    print(json.dumps({'checks': checks, 'failed': 0, 'cloudCalls': 0, 'dependencyCalls': 0, 'loadWindows': 0, 'localNodeBundles': 1}))


if __name__ == '__main__':
    main()
